/**
 * 문서 유형별 작성 템플릿과 가이드.
 *
 * 이 제품의 가장 큰 리스크는 "구성원이 문서를 등록하지 않거나 기록 품질이 낮은 것"이다.
 * 빈 입력칸 대신 유형별 템플릿과 작성 요령을 줘서 기록의 문턱을 낮추고 구조를 유도한다.
 *
 * ## 템플릿이 검색 품질에 닿는 경로
 *
 * 이 템플릿의 `##` 헤딩은 꾸미기가 아니다. 색인 파이프라인에 그대로 물린다.
 *
 * 1. 폼에 입력한 본문은 파일이 없으면 `content.md` 로 취급돼 **마크다운으로 파싱된다**
 *    (index-worker `pipeline.py` 의 `parse_document(content, "content.md")`).
 * 2. 청킹은 헤딩 단위로 자른다(`chunk.py` 의 `_split_by_headings`). 헤딩이 하나도 없으면
 *    문서 전체가 한 덩어리로 길이 분할될 뿐이라, 답변이 인용할 때 "이 문서의 어디"를
 *    가리키지 못한다.
 * 3. 헤딩은 `section_path` 가 되어 출처 카드와 지표 드릴다운에 그대로 보인다.
 * 4. **`chunk_tag` 가 헤딩 글자에 걸린다.** 태그 규칙은 청크 본문 부분 일치이고
 *    (`contracts/indexing/README.md` §5) 헤딩 줄도 청크 본문에 포함되므로,
 *    `## 결정 사항` 은 그 절을 `DECISION` 으로 만든다. 타임라인 발췌가 `DECISION` 청크만
 *    쓰기 때문에(같은 문서 §5) **결정 절이 없는 문서는 타임라인에 내용이 안 뜬다.**
 *
 * 그래서 절 이름을 아무렇게나 고르지 않았다. 아래 주석의 `→ TAG` 가 의도한 태그이고,
 * 실제 색인기(`parse_document` + `chunk_document`)에 넣어 확인한 결과다 — 네 유형 모두
 * 절 6개로 갈리고 각각 `DECISION` 절을 최소 하나 가진다. 헤딩이 없으면 청크 1개에
 * `section_path` 가 빈 문자열이다.
 *
 * 다만 태그는 부분 일치라 보장이 아니라 유도다 — 규칙 우선순위가
 * DECISION > ACTION_ITEM > DISCUSSION 이어서 어느 절이든 본문에 `결정`·`승인` 같은 낱말이
 * 들어가면 `DECISION` 으로 넘어간다. 예시 문구를 쓸 때 이걸 감안했다(아래 영향 범위 주석).
 *
 * ## 강제하지 않는다
 *
 * 템플릿을 의무화하면 작성 자체를 안 하게 된다. 새 문서에서 유형을 고를 때 본문이
 * 비어 있을 때만 넣고, 언제든 지우거나 통째로 바꿔 쓸 수 있다. 편집 중인 문서에는
 * 절대 끼워 넣지 않는다.
 */
export interface DocumentTemplate {
  /** 폼에 한 줄로 띄우는 안내. 이 유형에서 무엇이 검색을 좌우하는지만 말한다. */
  guide: string;
  /** 본문에 넣을 마크다운. 헤딩은 청크 경계·section_path·chunk_tag 가 된다. */
  body: string;
}

