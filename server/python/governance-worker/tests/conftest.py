# governance-worker 가 읽는 document 스키마 최소 부분(document·decision_conflicts) +
# 색인 본문을 읽어오는 indexing.document_chunk. 실제 마이그레이션 파일과 같은 제약을 쓴다.
SCHEMA = """
CREATE SCHEMA document;
CREATE TYPE document.document_type AS ENUM ('MEETING_NOTE', 'DECISION_RECORD', 'DESIGN_DOC', 'POLICY_DOC');
CREATE TABLE document.document (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200)           NOT NULL,
    content         TEXT                   NOT NULL,
    document_type   document.document_type NOT NULL,
    decision_status VARCHAR(30)            NOT NULL DEFAULT 'UNDECIDED',
    organization_id BIGINT                 NOT NULL,
    team_id         BIGINT,
    -- 상충 알림을 작성자 개인에게도 보내는 데 쓴다
    author_id       BIGINT,
    authored_at     DATE                   NOT NULL,
    current_version INT                    NOT NULL DEFAULT 1,
    deleted_at      TIMESTAMPTZ
);
CREATE TABLE document.document_version (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES document.document (id) ON DELETE CASCADE,
    version     INT    NOT NULL,
    content     TEXT   NOT NULL
);

CREATE TABLE document.decision_conflicts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_doc_id   BIGINT NOT NULL REFERENCES document.document (id) ON DELETE CASCADE,
    target_doc_id   BIGINT NOT NULL REFERENCES document.document (id) ON DELETE CASCADE,
    source_clause   TEXT NOT NULL,
    target_clause   TEXT NOT NULL,
    conflict_type   VARCHAR(50) NOT NULL,
    severity_score  NUMERIC(3, 2) NOT NULL,
    reasoning       TEXT NOT NULL,
    affected_teams  TEXT[] NOT NULL DEFAULT '{}',
    status          VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    -- V5__conflict_source_version.sql: 판정에 쓰인 source 문서의 판(NULL = 컬럼 생기기 전 기록)
    source_doc_version INT,
    resolved_by     VARCHAR(100),
    resolution_note TEXT,
    resolved_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- V4__decision_conflicts_unique.sql 과 같다
CREATE UNIQUE INDEX ux_conflict_pair ON document.decision_conflicts (source_doc_id, target_doc_id, (md5(source_clause)));

-- indexing.document_chunk 만 옮긴다(governance-worker 는 이 표만 읽는다)
CREATE SCHEMA indexing;
CREATE TYPE indexing.chunk_tag AS ENUM ('DECISION', 'DISCUSSION', 'ACTION_ITEM', 'BACKGROUND');
CREATE TABLE indexing.document_chunk (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id      BIGINT       NOT NULL,
    document_version INT          NOT NULL,
    chunk_no         INT          NOT NULL,
    content          TEXT         NOT NULL,
    section_path     VARCHAR(500),
    chunk_tag        indexing.chunk_tag,
    token_count      INT          NOT NULL,
    scope_key        VARCHAR(200) NOT NULL,
    search_vector    TSVECTOR     NOT NULL,
    vector_point_id  UUID         NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ux_chunk UNIQUE (document_id, document_version, chunk_no)
);
"""

# auth-service 가 소유하는 public 테이블 중 governance-worker 가 읽는 것만.
# auth-service 는 자기 스키마를 따로 두지 않고 public 을 그대로 쓴다(db.py 주석 참고).
PUBLIC_SCHEMA = """
CREATE TYPE user_status AS ENUM ('ACTIVE', 'DISABLED');
CREATE TABLE app_user (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email  VARCHAR(255) NOT NULL UNIQUE,
    name   VARCHAR(100) NOT NULL,
    status user_status  NOT NULL DEFAULT 'ACTIVE'
);
"""


def _database_url() -> str:
    url = os.environ.get("TEST_DATABASE_URL")
    if not url:
        if os.environ.get("CI"):
            pytest.fail("CI 에서는 TEST_DATABASE_URL 이 필요하다. 건너뛰면 DB 테스트가 조용히 빠진다")
        pytest.skip("TEST_DATABASE_URL 이 없어 DB 통합 테스트를 건너뛴다")
    if "test" not in urlparse(url).path:
        pytest.fail("TEST_DATABASE_URL 의 DB 이름에 test 가 들어가야 한다(document·indexing 스키마를 지우고 다시 만든다)")
    return url


@pytest.fixture
async def pool():
    url = _database_url()
    conn = await asyncpg.connect(url)
    try:
        await conn.execute("DROP SCHEMA IF EXISTS document CASCADE; DROP SCHEMA IF EXISTS indexing CASCADE;")
        await conn.execute("DROP TABLE IF EXISTS app_user CASCADE; DROP TYPE IF EXISTS user_status CASCADE;")
        await conn.execute(SCHEMA)
        await conn.execute(PUBLIC_SCHEMA)
    finally:
        await conn.close()
    db = await asyncpg.create_pool(url, min_size=1, max_size=8)
    yield db
    await db.close()


