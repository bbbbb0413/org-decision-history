-- 색인 작업 · 청크 (DB.dbml 그룹 4)
-- index-worker 가 indexing 스키마를 소유한다.
-- 서비스마다 자기 스키마를 갖게 해 Flyway 이력이 서로 간섭하지 않게 한다.

CREATE TYPE index_trigger AS ENUM ('DOCUMENT_UPLOAD', 'DOCUMENT_UPDATE', 'DOCUMENT_DELETE', 'BULK_INDEX', 'EXTERNAL_SYNC');
CREATE TYPE job_status    AS ENUM ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED');
CREATE TYPE index_stage   AS ENUM ('PARSE', 'CHUNK', 'EMBED', 'VECTOR_UPSERT', 'KEYWORD_INDEX');
CREATE TYPE chunk_tag     AS ENUM ('DECISION', 'DISCUSSION', 'ACTION_ITEM', 'BACKGROUND');

CREATE TABLE index_job (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_key       UUID          NOT NULL UNIQUE,
    trigger_type  index_trigger NOT NULL,
    status        job_status    NOT NULL DEFAULT 'PENDING',
    total_count   INT           NOT NULL DEFAULT 0,
    success_count INT           NOT NULL DEFAULT 0,
    fail_count    INT           NOT NULL DEFAULT 0,
    pending_count INT           NOT NULL DEFAULT 0,
    requested_by  BIGINT,
    requested_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    finished_at   TIMESTAMPTZ
);
CREATE INDEX ix_job_status ON index_job (status, requested_at DESC);

CREATE TABLE index_job_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    index_job_id     BIGINT       NOT NULL REFERENCES index_job (id) ON DELETE CASCADE,
    document_id      BIGINT       NOT NULL,
    document_version INT          NOT NULL,
    status           job_status   NOT NULL DEFAULT 'PENDING',
    stage            index_stage,
    failure_reason   VARCHAR(300),
    -- 암호화·손상·미지원 형식은 다시 시도해도 결과가 같으므로 false 로 둔다
    retryable        BOOLEAN      NOT NULL DEFAULT TRUE,
    retry_count      SMALLINT     NOT NULL DEFAULT 0,
    last_attempt_at  TIMESTAMPTZ,
    next_attempt_at  TIMESTAMPTZ,
    -- 멱등 키. 같은 이벤트가 두 번 와도 중복 벡터를 만들지 않는다 (기능 2.1)
    event_key        VARCHAR(120) NOT NULL UNIQUE
);
CREATE INDEX ix_jobitem_job   ON index_job_item (index_job_id);
CREATE INDEX ix_jobitem_doc   ON index_job_item (document_id);
CREATE INDEX ix_jobitem_retry ON index_job_item (status, retryable, next_attempt_at);

CREATE TABLE document_chunk (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id      BIGINT       NOT NULL,
    document_version INT          NOT NULL,
    chunk_no         INT          NOT NULL,
    content          TEXT         NOT NULL,
    section_path     VARCHAR(500),
    chunk_tag        chunk_tag,
    token_count      INT          NOT NULL,
    -- 권한 스코프 문자열. Qdrant payload 와 같은 형식을 쓴다
    scope_key        VARCHAR(200) NOT NULL,
    -- 전문검색 색인 (기능 2.1.6). 한국어 형태소 분석기가 없어 simple 설정을 쓴다
    search_vector    TSVECTOR     NOT NULL,
    vector_point_id  UUID         NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ux_chunk UNIQUE (document_id, document_version, chunk_no)
);
CREATE INDEX ix_chunk_scope ON document_chunk (scope_key);
CREATE INDEX ix_chunk_fts   ON document_chunk USING GIN (search_vector);
CREATE INDEX ix_chunk_doc   ON document_chunk (document_id);
