MIGRATIONS_DIR = Path(__file__).resolve().parents[1] / "migrations"
MIGRATION = MIGRATIONS_DIR / "V1__index_schema.sql"

# document-service V1 중 색인이 읽는 열만 옮겼다
DOCUMENT_SCHEMA = """
CREATE SCHEMA document;
CREATE TYPE document.document_type AS ENUM ('MEETING_NOTE', 'DECISION_RECORD', 'DESIGN_DOC', 'POLICY_DOC');
CREATE TABLE document.document (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200)           NOT NULL,
    content         TEXT                   NOT NULL,
    document_type   document.document_type NOT NULL,
    organization_id BIGINT                 NOT NULL,
    team_id         BIGINT,
    project_name    VARCHAR(100),
    authored_at     DATE                   NOT NULL,
    current_version INT                    NOT NULL DEFAULT 1,
    deleted_at      TIMESTAMPTZ
);
CREATE TABLE document.document_file (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id       BIGINT       NOT NULL REFERENCES document.document (id) ON DELETE CASCADE,
    version           INT          NOT NULL,
    storage_key       VARCHAR(500) NOT NULL UNIQUE,
    original_filename VARCHAR(255) NOT NULL,
    CONSTRAINT ux_docfile_ver UNIQUE (document_id, version)
);
"""


def _database_url() -> str:
    url = os.environ.get("TEST_DATABASE_URL")
    if not url:
        if os.environ.get("CI"):
            pytest.fail("CI 에서는 TEST_DATABASE_URL 이 필요하다. 건너뛰면 DB 테스트가 조용히 빠진다")
        pytest.skip("TEST_DATABASE_URL 이 없어 DB 통합 테스트를 건너뛴다")
    # 스키마를 지우고 다시 만든다. 개발용 DB 를 가리키는 실수를 막는다
    if "test" not in urlparse(url).path:
        pytest.fail("TEST_DATABASE_URL 의 DB 이름에 test 가 들어가야 한다(indexing·document 스키마를 지우고 다시 만든다)")
    return url


@pytest.fixture
async def pool():
    url = _database_url()
    conn = await asyncpg.connect(url)
    try:
        await conn.execute("DROP SCHEMA IF EXISTS indexing CASCADE; DROP SCHEMA IF EXISTS document CASCADE;")
        await conn.execute(DOCUMENT_SCHEMA)
        # Flyway 는 schemas=indexing 으로 이 파일들을 돌린다. 스키마 이름 없이 만든 객체가 indexing 에 생긴다
        await conn.execute("CREATE SCHEMA indexing; SET search_path TO indexing;")
        for migration in sorted(MIGRATIONS_DIR.glob("V*.sql")):
            await conn.execute(migration.read_text(encoding="utf-8"))
    finally:
        await conn.close()
    db = await asyncpg.create_pool(url, min_size=1, max_size=8)
    yield db
    await db.close()


