"""테스트 공통 준비물.

SourceResolver 의 권한 재확인·바운딩 박스 조회는 실제 PostgreSQL 이 필요하다.

    docker run -d --rm -p 55434:5432 -e POSTGRES_USER=test -e POSTGRES_PASSWORD=test \
        -e POSTGRES_DB=rag_service_test postgres:16.4-alpine
    TEST_DATABASE_URL=postgresql://test:test@localhost:55434/rag_service_test python -m pytest
"""
import os
from datetime import date
from urllib.parse import urlparse

import asyncpg
import pytest

# SourceResolver 가 읽는 document·indexing 스키마 최소 부분. 실제 마이그레이션 파일과 같은 제약을 쓴다.
SCHEMA = """
CREATE SCHEMA document;
CREATE TYPE document.document_type AS ENUM ('MEETING_NOTE', 'DECISION_RECORD', 'DESIGN_DOC', 'POLICY_DOC');
CREATE TABLE document.document (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200)           NOT NULL,
    document_type   document.document_type NOT NULL,
    organization_id BIGINT                 NOT NULL,
    team_id         BIGINT,
    authored_at     DATE                   NOT NULL,
    current_version INT                    NOT NULL DEFAULT 1,
    deleted_at      TIMESTAMPTZ
);
CREATE TABLE document.document_file (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES document.document (id) ON DELETE CASCADE,
    version     INT    NOT NULL
);

CREATE SCHEMA indexing;
CREATE TYPE indexing.chunk_tag AS ENUM ('DECISION', 'DISCUSSION', 'ACTION_ITEM', 'BACKGROUND');
CREATE TABLE indexing.document_chunk (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id      BIGINT       NOT NULL,
    document_version INT          NOT NULL,
    chunk_no         INT          NOT NULL,
    content          TEXT         NOT NULL,
    section_path     VARCHAR(500),
    chunk_tag        indexing.chunk_tag,
    token_count      INT          NOT NULL,
    scope_key        VARCHAR(200) NOT NULL,
    search_vector    TSVECTOR     NOT NULL,
    vector_point_id  UUID         NOT NULL,
    -- V3__chunk_bbox.sql 과 같다
    page_start       SMALLINT,
    page_end         SMALLINT,
    bboxes           JSONB,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ux_chunk UNIQUE (document_id, document_version, chunk_no)
);
"""


def _database_url() -> str:
    url = os.environ.get("TEST_DATABASE_URL")
    if not url:
        if os.environ.get("CI"):
            pytest.fail("CI 에서는 TEST_DATABASE_URL 이 필요하다. 건너뛰면 DB 테스트가 조용히 빠진다")
        pytest.skip("TEST_DATABASE_URL 이 없어 DB 통합 테스트를 건너뛴다")
    if "test" not in urlparse(url).path:
        pytest.fail("TEST_DATABASE_URL 의 DB 이름에 test 가 들어가야 한다(document·indexing 스키마를 지우고 다시 만든다)")
    return url


@pytest.fixture
async def pool():
    url = _database_url()
    conn = await asyncpg.connect(url)
    try:
        await conn.execute("DROP SCHEMA IF EXISTS document CASCADE; DROP SCHEMA IF EXISTS indexing CASCADE;")
        await conn.execute(SCHEMA)
    finally:
        await conn.close()
    db = await asyncpg.create_pool(url, min_size=1, max_size=8)
    yield db
    await db.close()


@pytest.fixture
def add_document(pool):
    async def add(
        *,
        title: str = "정책 문서",
        organization_id: int = 1,
        team_id: int | None = None,
        authored_at: date = date(2024, 3, 15),
        document_type: str = "POLICY_DOC",
        current_version: int = 1,
        with_file: bool = False,
    ) -> int:
        document_id = await pool.fetchval(
            "INSERT INTO document.document"
            " (title, document_type, organization_id, team_id, authored_at, current_version)"
            " VALUES ($1, $2::document.document_type, $3, $4, $5, $6) RETURNING id",
            title, document_type, organization_id, team_id, authored_at, current_version,
        )
        if with_file:
            await pool.execute(
                "INSERT INTO document.document_file (document_id, version) VALUES ($1, $2)",
                document_id, current_version,
            )
        return document_id

    return add


