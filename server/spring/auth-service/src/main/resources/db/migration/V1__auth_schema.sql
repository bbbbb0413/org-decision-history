-- 조직 · 사용자 · 역할 (DB.dbml 그룹 1)
-- auth-service 가 이 테이블들의 소유자다. 다른 서비스는 읽기만 한다.

CREATE TYPE user_status AS ENUM ('ACTIVE', 'DISABLED');
CREATE TYPE system_role AS ENUM ('SYSTEM_ADMIN', 'ORG_ADMIN', 'TEAM_ADMIN', 'MEMBER');

CREATE TABLE organization (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE team (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT       NOT NULL REFERENCES organization (id),
    name            VARCHAR(100) NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ux_team_org_name UNIQUE (organization_id, name)
);

CREATE TABLE app_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    name            VARCHAR(100) NOT NULL,
    organization_id BIGINT       REFERENCES organization (id),
    status          user_status  NOT NULL DEFAULT 'ACTIVE',
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_user_org ON app_user (organization_id);

CREATE TABLE user_team (
    user_id     BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    team_id     BIGINT      NOT NULL REFERENCES team (id)     ON DELETE CASCADE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    assigned_by BIGINT      REFERENCES app_user (id),
    PRIMARY KEY (user_id, team_id)
);
CREATE INDEX ix_user_team_team ON user_team (team_id);

CREATE TABLE user_role (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    role       system_role NOT NULL,
    granted_by BIGINT      REFERENCES app_user (id),
    granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ux_user_role UNIQUE (user_id, role)
);
