-- 접근 정책 · 감사 로그 (DB.dbml 그룹 3)
-- auth-service 가 권한 판정의 소유자다. 다른 서비스는 스코프 조회 API 로 물어본다.

CREATE TYPE policy_subject_type AS ENUM ('USER', 'ROLE', 'TEAM');
CREATE TYPE policy_scope_type   AS ENUM ('ORGANIZATION', 'TEAM', 'DOCUMENT');
CREATE TYPE audit_action        AS ENUM ('DOCUMENT_VIEW', 'DOCUMENT_SEARCH', 'FILE_DOWNLOAD_ISSUE', 'POLICY_CHANGE', 'ROLE_CHANGE');
CREATE TYPE audit_result        AS ENUM ('ALLOWED', 'DENIED');

-- 주체와 대상을 각각 세 개의 nullable 컬럼으로 나눈다.
-- 문자열 하나로 받으면 FK 를 걸 수 없어 DB 가 무결성을 강제하지 못한다.
-- scope_document_id 는 document 가 다른 서비스 소유라 FK 를 걸지 않는다.
CREATE TABLE access_policy (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type          policy_subject_type NOT NULL,
    subject_user_id       BIGINT REFERENCES app_user (id) ON DELETE CASCADE,
    subject_team_id       BIGINT REFERENCES team (id)     ON DELETE CASCADE,
    subject_role          system_role,
    scope_type            policy_scope_type   NOT NULL,
    scope_organization_id BIGINT REFERENCES organization (id) ON DELETE CASCADE,
    scope_team_id         BIGINT REFERENCES team (id)         ON DELETE CASCADE,
    scope_document_id     BIGINT,
    can_read              BOOLEAN     NOT NULL DEFAULT TRUE,
    created_by            BIGINT REFERENCES app_user (id),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_at            TIMESTAMPTZ,

    -- subject_type 에 맞는 컬럼 하나만 채워지게 강제한다
    CONSTRAINT ck_policy_subject CHECK (
        (subject_type = 'USER' AND subject_user_id IS NOT NULL AND subject_team_id IS NULL AND subject_role IS NULL) OR
        (subject_type = 'TEAM' AND subject_team_id IS NOT NULL AND subject_user_id IS NULL AND subject_role IS NULL) OR
        (subject_type = 'ROLE' AND subject_role    IS NOT NULL AND subject_user_id IS NULL AND subject_team_id IS NULL)
    ),
    CONSTRAINT ck_policy_scope CHECK (
        (scope_type = 'ORGANIZATION' AND scope_organization_id IS NOT NULL AND scope_team_id IS NULL AND scope_document_id IS NULL) OR
        (scope_type = 'TEAM'         AND scope_team_id         IS NOT NULL AND scope_organization_id IS NULL AND scope_document_id IS NULL) OR
        (scope_type = 'DOCUMENT'     AND scope_document_id     IS NOT NULL AND scope_organization_id IS NULL AND scope_team_id IS NULL)
    )
);
CREATE INDEX ix_policy_subject   ON access_policy (subject_type, subject_user_id, subject_team_id, subject_role);
CREATE INDEX ix_policy_scope_doc ON access_policy (scope_type, scope_document_id);
CREATE INDEX ix_policy_active    ON access_policy (revoked_at);

CREATE TABLE audit_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id       BIGINT REFERENCES app_user (id),
    action         audit_action NOT NULL,
    target_type    VARCHAR(50),
    target_id      BIGINT,
    result         audit_result NOT NULL,
    reason         VARCHAR(200),
    correlation_id VARCHAR(64),
    occurred_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_time   ON audit_log (occurred_at DESC);
CREATE INDEX ix_audit_actor  ON audit_log (actor_id, occurred_at DESC);
CREATE INDEX ix_audit_target ON audit_log (target_id);
CREATE INDEX ix_audit_corr   ON audit_log (correlation_id);
