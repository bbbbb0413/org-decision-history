-- 대화 · 메시지 · 출처 · 피드백 (DB.dbml 그룹 5)
-- chat-service 가 chat 스키마를 소유한다.

CREATE TYPE message_role   AS ENUM ('USER', 'ASSISTANT');
CREATE TYPE answer_status  AS ENUM ('OK', 'NO_EVIDENCE', 'LOW_CONFIDENCE', 'DEGRADED', 'RATE_LIMITED');
CREATE TYPE feedback_rating AS ENUM ('HELPFUL', 'NOT_HELPFUL');

CREATE TABLE conversation (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   BIGINT       NOT NULL,
    title      VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);
CREATE INDEX ix_conv_owner ON conversation (owner_id, updated_at DESC);

CREATE TABLE message (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT       NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    role            message_role NOT NULL,
    content         TEXT         NOT NULL,
    -- 대화 맥락을 합쳐 만든 독립형 질문 (기능 4.1.2). 무엇으로 검색했는지 남긴다.
    rewritten_query TEXT,
    model_name      VARCHAR(100),
    answer_status   answer_status,
    latency_ms      INT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_msg_conv ON message (conversation_id, created_at);

-- 답변에 쓴 출처 (기능 4.1.7).
-- 제목·유형·작성일은 document 조인으로 얻으므로 중복 저장하지 않는다.
CREATE TABLE answer_source (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id       BIGINT       NOT NULL REFERENCES message (id) ON DELETE CASCADE,
    document_id      BIGINT       NOT NULL,
    document_version INT          NOT NULL,
    chunk_no         INT          NOT NULL,
    similarity       NUMERIC(5,4) NOT NULL,
    rank             SMALLINT     NOT NULL,
    CONSTRAINT ux_source_rank UNIQUE (message_id, rank)
);
CREATE INDEX ix_source_doc ON answer_source (document_id);

CREATE TABLE answer_feedback (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT          NOT NULL UNIQUE REFERENCES message (id) ON DELETE CASCADE,
    user_id    BIGINT          NOT NULL,
    rating     feedback_rating NOT NULL,
    reason     VARCHAR(500),
    created_at TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ     NOT NULL DEFAULT now()
);
