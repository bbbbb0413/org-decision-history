-- 상충 정보 분석 결과 캐시 (DB.dbml 그룹 6)
--
-- 타임라인 사건 자체는 document 를 작성일 순으로 조회해 만들므로 테이블을 두지 않는다.
-- 상충 판정만 비용이 크고 결과가 안정적이어서 캐시한다.
-- 어느 쪽이 옳은지는 저장하지 않는다. 판단은 사용자의 몫이다.

CREATE TABLE timeline_conflict (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_normalized VARCHAR(200) NOT NULL,
    -- 권한 스코프 해시. 범위가 다르면 보이는 문서가 달라 결과를 공유할 수 없다.
    scope_hash       CHAR(64)     NOT NULL,
    document_a_id    BIGINT       NOT NULL,
    document_b_id    BIGINT       NOT NULL,
    difference       VARCHAR(500) NOT NULL,
    detected_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at       TIMESTAMPTZ  NOT NULL
);
CREATE INDEX ix_conflict_topic  ON timeline_conflict (topic_normalized, scope_hash);
CREATE INDEX ix_conflict_expiry ON timeline_conflict (expires_at);
