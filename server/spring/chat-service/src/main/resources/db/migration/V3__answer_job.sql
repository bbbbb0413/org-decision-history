-- 답변 생성 작업 (Kafka job 분산 + Redis Stream fan-out/resume 을 위한 진행 상태)
-- chat.message.answer_status(답변 품질)와는 별개 개념이라 섞지 않는다.

CREATE TYPE job_status AS ENUM ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED');

CREATE TABLE answer_job (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_key               UUID        NOT NULL UNIQUE,
    conversation_id       BIGINT      NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    user_id               BIGINT      NOT NULL,
    question              TEXT        NOT NULL,
    status                job_status  NOT NULL DEFAULT 'PENDING',
    assistant_message_id  BIGINT      REFERENCES message (id),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_answer_job_conv ON answer_job (conversation_id, created_at DESC);
