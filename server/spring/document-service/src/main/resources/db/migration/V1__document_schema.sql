-- 문서 · 버전 · 원본 파일 · 아웃박스 (DB.dbml 그룹 2)
-- document-service 가 이 테이블들의 소유자다.
--
-- 서비스 간 FK 는 걸지 않는다. organization/team/app_user 는 auth-service 소유이고
-- 마이그레이션 순서를 서로 강제하면 배포가 묶이기 때문이다.
-- 논리적 관계는 DB.dbml 에 남기고, 물리 제약은 소유 서비스 안에서만 건다.

CREATE TYPE document_type    AS ENUM ('MEETING_NOTE', 'DECISION_RECORD', 'DESIGN_DOC', 'POLICY_DOC');
CREATE TYPE decision_status  AS ENUM ('CURRENT', 'CHANGED', 'DEPRECATED', 'UNDECIDED');
CREATE TYPE document_origin  AS ENUM ('MANUAL', 'IMPORT', 'EXTERNAL_SYNC');
CREATE TYPE outbox_event_type AS ENUM ('DOCUMENT_CREATED', 'DOCUMENT_UPDATED', 'DOCUMENT_DELETED', 'PERMISSION_CHANGED');

CREATE TABLE document (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                  VARCHAR(200)    NOT NULL,
    content                TEXT            NOT NULL,
    document_type          document_type   NOT NULL,
    decision_status        decision_status NOT NULL DEFAULT 'UNDECIDED',
    organization_id        BIGINT          NOT NULL,
    team_id                BIGINT,
    project_name           VARCHAR(100),
    author_id              BIGINT,
    author_name            VARCHAR(100)    NOT NULL,
    authored_at            DATE            NOT NULL,
    origin                 document_origin NOT NULL DEFAULT 'MANUAL',
    external_repository_id BIGINT,
    external_document_key  VARCHAR(500),
    current_version        INT             NOT NULL DEFAULT 1,
    created_at             TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ     NOT NULL DEFAULT now(),
    deleted_at             TIMESTAMPTZ
);
CREATE INDEX ix_doc_scope    ON document (organization_id, team_id);
CREATE INDEX ix_doc_type     ON document (document_type);
CREATE INDEX ix_doc_status   ON document (decision_status);
CREATE INDEX ix_doc_authored ON document (authored_at);
CREATE INDEX ix_doc_deleted  ON document (deleted_at);
CREATE UNIQUE INDEX ux_doc_external
    ON document (external_repository_id, external_document_key)
    WHERE external_repository_id IS NOT NULL;

CREATE TABLE document_version (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     BIGINT          NOT NULL REFERENCES document (id) ON DELETE CASCADE,
    version         INT             NOT NULL,
    title           VARCHAR(200)    NOT NULL,
    content         TEXT            NOT NULL,
    decision_status decision_status NOT NULL,
    change_note     VARCHAR(300),
    created_by      BIGINT,
    created_at      TIMESTAMPTZ     NOT NULL DEFAULT now(),
    CONSTRAINT ux_docver UNIQUE (document_id, version)
);

CREATE TABLE document_file (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id       BIGINT       NOT NULL REFERENCES document (id) ON DELETE CASCADE,
    version           INT          NOT NULL,
    storage_key       VARCHAR(500) NOT NULL UNIQUE,
    original_filename VARCHAR(255) NOT NULL,
    mime_type         VARCHAR(100) NOT NULL,
    size_bytes        BIGINT       NOT NULL,
    checksum_sha256   CHAR(64)     NOT NULL,
    uploaded_by       BIGINT,
    uploaded_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ux_docfile_ver UNIQUE (document_id, version)
);

-- 문서 저장과 같은 트랜잭션에 이벤트를 남겨 유실을 막는다.
-- 발행기가 published_at 이 비어 있는 행을 Redis Stream 으로 보낸다.
CREATE TABLE document_outbox (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_id BIGINT            NOT NULL,
    event_type   outbox_event_type NOT NULL,
    payload      JSONB             NOT NULL,
    occurred_at  TIMESTAMPTZ       NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ
);
CREATE INDEX ix_outbox_unpublished ON document_outbox (occurred_at) WHERE published_at IS NULL;
