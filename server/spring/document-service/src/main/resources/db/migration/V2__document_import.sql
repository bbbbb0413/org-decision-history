-- 일괄 가져오기 (DB.dbml 그룹 6, 기능 8.1)
-- document-service 가 소유한다. 원본 파일 실체는 객체 저장소에 두고, 재시도 가능한
-- 실패 건만 원본을 임시 보관해 재처리 시 재업로드 없이 다시 시도할 수 있게 한다.

CREATE TYPE job_status          AS ENUM ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED');
CREATE TYPE import_item_status  AS ENUM ('SUCCESS', 'FAILED');

CREATE TABLE import_job (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_key               UUID          NOT NULL UNIQUE,
    requested_by          BIGINT        NOT NULL,
    default_document_type document_type NOT NULL,
    organization_id       BIGINT        NOT NULL,
    team_id               BIGINT,
    file_count            INT           NOT NULL,
    success_count         INT           NOT NULL DEFAULT 0,
    fail_count            INT           NOT NULL DEFAULT 0,
    status                job_status    NOT NULL DEFAULT 'PENDING',
    requested_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    finished_at           TIMESTAMPTZ
);

CREATE TABLE import_item (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_job_id  BIGINT             NOT NULL REFERENCES import_job (id) ON DELETE CASCADE,
    filename       VARCHAR(255)       NOT NULL,
    document_id    BIGINT             REFERENCES document (id),
    status         import_item_status NOT NULL,
    failure_reason VARCHAR(300),
    -- 암호화·손상·미지원 형식·크기 초과는 false 다. 재시도해도 결과가 같다.
    retryable      BOOLEAN            NOT NULL DEFAULT TRUE,
    -- 재시도 가능한 실패 건의 원본을 임시 보관한 키. 성공 건과 재시도 불가 건은 null 이다.
    staging_key    VARCHAR(500),
    processed_at   TIMESTAMPTZ        NOT NULL DEFAULT now()
);
CREATE INDEX ix_importitem_job ON import_item (import_job_id);
