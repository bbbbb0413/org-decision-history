-- 정책 / 의사결정 상충 감지 (F-03 Conflict Detector)
-- 신규/개정 문서가 기존 정책과 모순(Contradiction)을 일으키는지 분석한 결과를 기록한다.

CREATE TABLE decision_conflicts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_doc_id   BIGINT NOT NULL REFERENCES document (id) ON DELETE CASCADE,
    target_doc_id   BIGINT NOT NULL REFERENCES document (id) ON DELETE CASCADE,
    source_clause   TEXT NOT NULL,
    target_clause   TEXT NOT NULL,
    conflict_type   VARCHAR(50) NOT NULL,
    severity_score  NUMERIC(3, 2) NOT NULL,
    reasoning       TEXT NOT NULL,
    affected_teams  TEXT[] NOT NULL DEFAULT '{}',
    status          VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    resolved_by     VARCHAR(100),
    resolution_note TEXT,
    resolved_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ix_conflict_source ON decision_conflicts (source_doc_id);
CREATE INDEX ix_conflict_target ON decision_conflicts (target_doc_id);
CREATE INDEX ix_conflict_status ON decision_conflicts (status);
CREATE INDEX ix_conflict_created ON decision_conflicts (created_at DESC);
